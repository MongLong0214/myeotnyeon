def _hook(eid, ep):
    """Resolve an episode's `hook`: lines → head, narration → first sentence of the first cue, split → its captions."""
    h = ep['hook']
    assert h.get('style', 'house') in ('house', 'outcome'), f'{eid}: unknown hook style'
    assert len(h['lines']) == 2, f'{eid}: house/outcome headers take exactly 2 lines'
    ep['head'] = list(h['lines'])
    cid, scene, na, cl, pad, p = ep['cues'][0]
    ep['cues'][0] = (cid, scene, [h['narration'], *na], cl, pad, p)
    if 'split' in h:
        ep.setdefault('split', {})[f'{cid}_1'] = h['split']


